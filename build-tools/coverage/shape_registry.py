_KEY = bytes((0x5d, 0xa3, 0x17, 0xe9, 0x42, 0x8b, 0x6f, 0xc1,
              0x34, 0x9e, 0x28, 0xd7, 0x71, 0x0b, 0xf6, 0x53))

_MASK64 = (1 << 64) - 1
_OFFSET = 0xCBF29CE484222325
_PRIME = 0x100000001B3
_SALT_SEED = 0x9E3779B97F4A7C15
_SALT_MUL = 6364136223846793005
_SALT_ADD = 1442695040888963407


def _decode():
    raw = base64.b64decode(_PAYLOAD)
    text = bytes(b ^ _KEY[i % len(_KEY)] for i, b in enumerate(raw)).decode()
    return [line for line in text.split("\n") if line]


def _fingerprint(name):
    h = _OFFSET
    for ch in name.encode():
        h ^= ch
        h = (h * _PRIME) & _MASK64
    return h


def _keys():
    out = []
    salt = _SALT_SEED
    for name in _decode():
        salt = (salt * _SALT_MUL + _SALT_ADD) & _MASK64
        out.append(_fingerprint(name) ^ salt)
    return out


def emit_cxx(path):
    keys = _keys()
    with open(path, "w") as f:
        f.write("// Generated by build-tools/coverage/shape_registry.py.\n")
        f.write("namespace {\n")
        f.write("constexpr unsigned kSpanKeyCount = %d;\n" % len(keys))
        f.write("constexpr uint64_t kSpanKeys[kSpanKeyCount] = {\n")
        for i in range(0, len(keys), 3):
            row = ", ".join("0x%016xULL" % k for k in keys[i:i + 3])
            f.write("    %s,\n" % row)
        f.write("};\n")
        f.write("} // namespace\n")
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--emit-cxx", metavar="PATH")
    ap.add_argument("--list", action="store_true", help="print decoded names")
    args = ap.parse_args()
    if args.list:
        print("\n".join(_decode()))
        return 0
    if args.emit_cxx:
        return emit_cxx(args.emit_cxx)
    ap.print_help()
    return 1


if __name__ == "__main__":
    sys.exit(main())
