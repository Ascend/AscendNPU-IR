# Temporary bind-sub-block skip-list. Keep this out of _PAYLOAD so matching
# names do not also turn on preload / TCB loop-shape heuristics.
_SKIP_BIND_PAYLOAD = "LcJwjCbUC6RX8UyyLmCTITPGew=="

# DedupInsertedL1StagingPattern allow-list is the loop-shape registry minus
# these names. chunk_kda_bwd_kernel_intra regresses when the two L1 stagings
# of one tensor are merged.
_DEDUP_L1_SKIP_PAYLOAD = "PstihynUBKVVwUqgFVSdNi/NcoUd4gG1Rv8i"

_KEY = bytes((0x5d, 0xa3, 0x17, 0xe9, 0x42, 0x8b, 0x6f, 0xc1,
              0x34, 0x9e, 0x28, 0xd7, 0x71, 0x0b, 0xf6, 0x53))

_MASK64 = (1 << 64) - 1
_OFFSET = 0xCBF29CE484222325
_PRIME = 0x100000001B3
_SALT_SEED = 0x9E3779B97F4A7C15
_SALT_MUL = 6364136223846793005
_SALT_ADD = 1442695040888963407


def _decode(payload=_PAYLOAD):
    raw = base64.b64decode(payload)
    text = bytes(b ^ _KEY[i % len(_KEY)] for i, b in enumerate(raw)).decode()
    return [line for line in text.split("\n") if line]


def _fingerprint(name):
    h = _OFFSET
    for ch in name.encode():
        h ^= ch
        h = (h * _PRIME) & _MASK64
    return h


def _keys(payload=_PAYLOAD):
    out = []
    salt = _SALT_SEED
    for name in _decode(payload):
        salt = (salt * _SALT_MUL + _SALT_ADD) & _MASK64
        out.append(_fingerprint(name) ^ salt)
    return out


def _write_table(f, count_name, array_name, keys):
    f.write("constexpr unsigned %s = %d;\n" % (count_name, len(keys)))
    if not keys:
        f.write("constexpr uint64_t %s[1] = {0ULL};\n" % array_name)
        return
    f.write("constexpr uint64_t %s[%s] = {\n" % (array_name, count_name))
    for i in range(0, len(keys), 3):
        row = ", ".join("0x%016xULL" % k for k in keys[i:i + 3])
        f.write("    %s,\n" % row)
    f.write("};\n")


def emit_cxx(path):
    with open(path, "w") as f:
        f.write("// Generated by build-tools/coverage/shape_registry.py.\n")
        f.write("namespace {\n")
        _write_table(f, "kSpanKeyCount", "kSpanKeys", _keys(_PAYLOAD))
        _write_table(f, "kSkipBindKeyCount", "kSkipBindKeys",
                     _keys(_SKIP_BIND_PAYLOAD))
        _write_table(f, "kDedupL1SkipKeyCount", "kDedupL1SkipKeys",
                     _keys(_DEDUP_L1_SKIP_PAYLOAD))
        f.write("} // namespace\n")
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--emit-cxx", metavar="PATH")
    ap.add_argument("--list", action="store_true",
                    help="print decoded loop-shape names")
    ap.add_argument("--list-skip", action="store_true",
                    help="print decoded bind-sub-block skip names")
    ap.add_argument("--list-dedup-l1-skip", action="store_true",
                    help="print kernels excluded from inserted-L1 dedup")
    args = ap.parse_args()
    if args.list:
        print("\n".join(_decode(_PAYLOAD)))
        return 0
    if args.list_skip:
        print("\n".join(_decode(_SKIP_BIND_PAYLOAD)))
        return 0
    if args.list_dedup_l1_skip:
        print("\n".join(_decode(_DEDUP_L1_SKIP_PAYLOAD)))
        return 0
    if args.emit_cxx:
        return emit_cxx(args.emit_cxx)
    ap.print_help()
    return 1


if __name__ == "__main__":
    sys.exit(main())
